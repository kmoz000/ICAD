auto intent_name(DesignIntent intent) -> std::string_view {
    if (intent == DesignIntent::robotic_arm)
        return "ROBOTIC_ARM";
    if (intent == DesignIntent::bridge)
        return "BRIDGE";
    return "GENERIC_PART";
}

auto conceptualize_json(std::string_view prompt) -> std::string {
    const auto prompt_copy = source_comment(prompt);
    std::size_t raw_words = 0;
    {
        std::istringstream words{prompt_copy};
        for (std::string word; words >> word;)
            ++raw_words;
    }
    auto compressed = compressed_prompt_tokens(prompt_copy);
    const auto compressed_count = compressed.array() == nullptr ? std::size_t{0}
                                                                 : compressed.array()->size();
    const double compression_ratio = raw_words == 0
                                         ? 1.0
                                         : static_cast<double>(compressed_count) /
                                               static_cast<double>(raw_words);
    return json::serialize(object({
        {"schema", "icad.agent.concept.v1"},
        {"conceptualIterations", 1.0},
        {"rawInput", prompt_copy},
        {"rawWordCount", static_cast<double>(raw_words)},
        {"compressedTokenCount", static_cast<double>(compressed_count)},
        {"compressionRatio", compression_ratio},
        {"compressedTokens", std::move(compressed)},
        {"blueprintReading", object({
             {"titleBlock", array({"design identity", "units and scale", "material callouts",
                                    "general tolerances", "notes and revision"})},
             {"billOfMaterials", array({"named components", "quantity", "material",
                                         "assembly ownership"})},
             {"dimensions", array({"size dimensions", "location dimensions",
                                    "linear and angular tolerances", "diameter and radius"})},
             {"views", array({"choose primary view with clearest detail and least hidden lines",
                               "use sufficient front/top/side orthographic views",
                               "use section view for hidden internal detail",
                               "use auxiliary view for true inclined-surface shape"})},
         })},
        {"conceptualRequest",
         "Expand the compressed tokens once into a complete component hierarchy, spatial envelope, "
         "size/location dimensions, materials, kinematic graph, constraints, manufacturing intent, "
         "and inspection scene. Then emit only dependency-ordered ICAD grammar."},
        {"outputContract", object({
             {"format", "ICAD_GRAMMAR_ONLY"},
             {"allowMarkdown", false},
             {"allowProse", false},
             {"requiredOrder", array({"PROJECT and UNITS", "PARAMETER and ANGLE",
                                       "POINT3 and VECTOR", "MATERIAL",
                                       "BODY: SKETCH then PAD or POCKET history",
                                       "POSE, JOINT, CONSTRAINT and MATE",
                                       "SCENE, TRACK and KEYFRAME"})},
         })},
        {"visualFeedback", object({{"available", false},
                                    {"requiredSchema", "icad.visual.snapshot.v1"},
                                    {"next", "Compile source and call icad.visualize directly"}})},
        {"iterationProtocol", array({
             "Run this conceptualization pass exactly once",
             "Emit one complete ICAD source document only",
             "Compile and repair stable diagnostics without reconceptualizing",
             "Call icad.visualize and consume icad.visual.snapshot.v1",
             "Revise named parameters, profiles, bodies, joints, or scenes based on view evidence",
             "Repeat compile and visual feedback until silhouette, body identity, bounds, and joints match intent",
             "Run engineering review and build only after visual acceptance",
         })},
    }));
}

auto bootstrap(std::string_view prompt) -> BootstrapResult {
    const auto normalized = lowercase(prompt);
    DesignIntent intent = DesignIntent::generic_part;
    if ((normalized.contains("robot") && normalized.contains("arm")) ||
        normalized.contains("manipulator") || normalized.contains("gripper")) {
        intent = DesignIntent::robotic_arm;
    } else if (normalized.contains("bridge") || normalized.contains("viaduct")) {
        intent = DesignIntent::bridge;
    }
    std::string source;
    if (intent == DesignIntent::robotic_arm)
        source = std::string{templates::robotic_arm};
    else if (intent == DesignIntent::bridge)
        source = std::string{templates::bridge};
    else
        source = generic_source();

    source = "# Agent prompt: " + source_comment(prompt) + "\n# Embedded template: " +
             std::string{intent_name(intent)} + "\n" + source;

    const auto compilation = compiler::compile(source);
    const double confidence = intent == DesignIntent::generic_part ? 0.55 : 0.98;
    const auto plan = object({
        {"schema", "icad.agent.bootstrap.v1"},
        {"prompt", std::string{prompt}},
        {"intent", std::string{intent_name(intent)}},
        {"confidence", confidence},
        {"sourceReady", compilation.ok()},
        {"source", source},
        {"sourceProvenance", "prompt and selected template are embedded as source comments"},
        {"promptUnderstanding", prompt_understanding(normalized, intent)},
        {"acceptanceCriteria", requirements(intent)},
        {"editableParameters", compilation.ok() ? editable_parameters(*compilation.ir_project)
                                                  : json::Value{json::Value::Array{}}},
        {"editableAngles", compilation.ok() ? editable_angles(*compilation.ir_project)
                                              : json::Value{json::Value::Array{}}},
        {"parameterStrategy", "Edit named PARAMETER and ANGLE declarations before changing topology"},
        {"preferredTool", "icad.agent.create"},
        {"nextTool", "icad.agent.review"},
        {"workflow", array({"agent.create"})},
        {"fallbackWorkflow", array({"bootstrap", "review", "project.write", "project.build"})},
        {"expectedModelIterations", intent == DesignIntent::generic_part ? 2.0 : 1.0},
    });
    return {intent, std::move(source), json::serialize(plan)};
}

auto review_json(std::string_view source) -> std::string {
    const auto compilation = compiler::compile(source);
    if (!compilation.ok()) {
        const auto parsed = json::parse(ai::diagnostics_json(source));
        return json::serialize(object({
            {"schema", "icad.agent.review.v1"},
            {"ready", false},
            {"stage", "compile"},
            {"diagnostics", parsed.ok() ? std::move(*parsed.value) : json::Value{nullptr}},
            {"nextActions", array({"Repair only the reported source locations", "Call icad.agent.review again"})},
        }));
    }

    const auto& project = *compilation.ir_project;
    const auto constraint_results = constraints::validate(project);
    const auto manufacturing_report = manufacturing::validate(project);
    const auto topology = cad::build_topology(project);
    const auto topology_validation = cad::validate_topology(topology);
    const auto metrics = cad::analyze(project);
    const auto interference =
        cad::analyze_intersections(project, project.tolerance.linear_mm);
    const bool constraints_passed = constraints::all_passed(constraint_results);
    const bool ready = constraints_passed && manufacturing_report.passed &&
                       topology_validation.valid() && !metrics.parts.empty();

    json::Value::Array failed_constraints;
    for (const auto& constraint : constraint_results) {
        if (!constraint.passed)
            failed_constraints.push_back(object({{"name", constraint.name},
                                                 {"message", constraint.message}}));
    }
    json::Value::Array manufacturing_issues;
    for (const auto& issue : manufacturing_report.issues) {
        manufacturing_issues.push_back(object({{"code", issue.code}, {"subject", issue.subject},
                                                {"message", issue.message}}));
    }
    json::Value::Array actions;
    if (!constraints_passed)
        actions.emplace_back("Repair failed constraints using named points, vectors, angles, or parameters");
    if (!manufacturing_report.passed)
        actions.emplace_back("Resolve manufacturing errors before export");
    if (!topology_validation.valid())
        actions.emplace_back("Repair invalid topology before export");
    if (interference.penetrating_part_pairs != 0)
        actions.emplace_back("Review reported assembly penetrations; joint hardware overlap may be intentional");
    if (ready)
        actions.emplace_back("Commit the exact source revision and call icad.project.build");

    return json::serialize(object({
        {"schema", "icad.agent.review.v1"},
        {"ready", ready},
        {"stage", ready ? "build" : "engineering"},
        {"project", project.name},
        {"summary", object({{"bodies", static_cast<double>(project.bodies.size())},
                             {"instances", static_cast<double>(project.instances.size())},
                             {"joints", static_cast<double>(project.joints.size())},
                             {"degreesOfFreedom", static_cast<double>(std::ranges::count_if(
                                 project.joints, [](const auto& joint) {
                                     return joint.kind != compiler::ir::JointKind::fixed;
                                 }))},
                             {"solids", static_cast<double>(topology.solids.size())},
                             {"exactFaces", static_cast<double>(topology.face_count())},
                             {"volumeMm3", metrics.volume_mm3}})},
        {"checks", object({{"constraintsPassed", constraints_passed},
                            {"manufacturingPassed", manufacturing_report.passed},
                            {"topologyValid", topology_validation.valid()},
                            {"penetratingPartPairs",
                             static_cast<double>(interference.penetrating_part_pairs)},
                            {"surfaceContactOnlyPartPairs",
                             static_cast<double>(interference.surface_contact_only_part_pairs)}})},
        {"failedConstraints", json::Value{std::move(failed_constraints)}},
        {"manufacturingIssues", json::Value{std::move(manufacturing_issues)}},
        {"designMap", design_map(project)},
        {"nextActions", json::Value{std::move(actions)}},
    }));
}

