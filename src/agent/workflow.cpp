[[nodiscard]] auto object(std::initializer_list<json::Value::Object::value_type> values)
    -> json::Value {
    return json::Value{json::Value::Object{values}};
}

[[nodiscard]] auto array(std::initializer_list<json::Value> values) -> json::Value {
    return json::Value{json::Value::Array{values}};
}

[[nodiscard]] auto strings(const std::vector<std::string>& values) -> json::Value {
    json::Value::Array result;
    result.reserve(values.size());
    for (const auto& value : values) {
        result.emplace_back(value);
    }
    return json::Value{std::move(result)};
}

[[nodiscard]] auto lowercase(std::string_view text) -> std::string {
    std::string result{text};
    std::ranges::transform(result, result.begin(),
                           [](unsigned char character) { return static_cast<char>(std::tolower(character)); });
    return result;
}

[[nodiscard]] auto source_comment(std::string_view text) -> std::string {
    std::string result;
    result.reserve(std::min<std::size_t>(text.size(), 512));
    for (const char raw_character : text) {
        const auto character = static_cast<unsigned char>(raw_character);
        if (result.size() == 512)
            break;
        if (character == '\n' || character == '\r' || character == '\t' ||
            character < 0x20U || character == 0x7fU) {
            result.push_back(' ');
        } else {
            result.push_back(static_cast<char>(character));
        }
    }
    return result;
}

